-- The clinic database as the API's entities define it, with the MRN and invoice-number sequences
-- and the one-live-invoice-per-visit index (formerly schema.sql). Generated from an empty database
-- (Hibernate ddl-auto=create, then pg_dump).
-- An existing database without Flyway's history is taken as already at this version
-- (spring.flyway.baseline-on-migrate); a new one, as in production, is built from it.

CREATE TABLE public.appointment (
    appointment_date date NOT NULL,
    appointment_time time(0) without time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    department_id bigint,
    updated_at timestamp(6) with time zone,
    id uuid NOT NULL,
    patient_id uuid NOT NULL,
    status character varying(20) NOT NULL,
    reason character varying(500),
    created_by character varying(255),
    doctor_user_id character varying(255) NOT NULL,
    updated_by character varying(255),
    CONSTRAINT appointment_status_check CHECK (((status)::text = ANY ((ARRAY['SCHEDULED'::character varying, 'CONFIRMED'::character varying, 'CHECKED_IN'::character varying, 'IN_PROGRESS'::character varying, 'COMPLETED'::character varying, 'CANCELLED'::character varying, 'NO_SHOW'::character varying])::text[])))
);

